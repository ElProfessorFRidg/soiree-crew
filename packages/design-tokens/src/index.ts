type Bezier = readonly [number, number, number, number];

function parseBezier(css: string): Bezier {
  const match = /cubic-bezier\(([^)]+)\)/.exec(css);
  const parts = (match?.[1] ?? "0,0,1,1").split(",").map((part) => Number.parseFloat(part));
  return [parts[0] ?? 0, parts[1] ?? 0, parts[2] ?? 1, parts[3] ?? 1];
}

