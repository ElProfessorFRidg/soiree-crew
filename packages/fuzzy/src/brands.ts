import type { CatalogueDrink, DrinkGroup, GlassName } from "./catalogue";

// More of what people order, country by country. Strength as printed on the label sold in that
// country (Smirnoff Red is 37.5 % in Europe, 40 % in the US: two entries would be noise, the
// European one is kept and the label's own figure stays editable). `countries` lists where the
// drink is a household name, so the add sheet shows those first; it never hides the others.
// ISO 3166 codes, the same as the legal country setting.

type Row = [id: string, brand: string, abv: number, volumeMl: number, glass: GlassName, aliases: readonly string[], countries: readonly string[], sizes?: readonly number[]];

const rows = (group: DrinkGroup, list: readonly Row[]): CatalogueDrink[] =>
  list.map(([id, brand, abv, volumeMl, glass, aliases, countries, sizes]) => ({
    id,
    brand,
    group,
    abv: abv / 100,
    volumeMl,
    glass,
    aliases,
    countries,
    ...(sizes ? { sizes } : {}),
    ...(glass === "can" ? { can: true } : {}),
  }));

